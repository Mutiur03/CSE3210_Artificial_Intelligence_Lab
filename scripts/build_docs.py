def refs(*items: tuple[str, str]) -> str:
    return ", ".join(f"`{R(f, n)}`" for f, n in items)


def qa(q: str, a: str, *items: tuple[str, str]) -> str:
    tail = f"\n   Code: {refs(*items)}" if items else ""
    return f"**Q. {q}**\n\n**A.** {a}{tail}\n"


